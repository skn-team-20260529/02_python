#비교연산
# A > B : A가 B보다 크면 T, 아니면 F
# A >= B : A가 B 이상이면 T, 아니면 F
# A < B
# A <= B :
# A == B : A, B가 같으면 T, 아니면 F
# A != B : A, B가 같지 않으면 T, 아니면 F

print("1 > 0.5:", 1 > 0.5)  # T
print("1 < 0.5:", 1 < 0.5) # F
print("1 >= 0.5:", 1 >= 0.5) #T
print("1 <= 0.5:", 1 <= 0.5) #F
print("1 == 1:", 1 == 1) #T
print("1 != 1:", 1 != 1) #F

